"""生成 `<bin_dir>/grok-<账号名>`。

启动命令是 config.json 的派生物。内容由账号名、目录、代理、环境变量和固定参数决定，
内容相同即视为没有变化。第 2 行的受管标记用来区分本工具生成的文件和用户自己的同名文件：
没有标记的文件不覆盖、不删除。

Grok 在沙箱启动时拒绝符号链接形式的 GROK_HOME（用户指南 18-sandbox.md），
所以脚本在 exec 之前拒绝软链。脚本调用 PATH 里的 grok，不把程序复制进账号目录。
"""

import os
import shlex
from typing import Dict, List, Optional

from .config import NETCHECK_SKIP_ENV, PROXY_INHERIT, PROXY_OFF, PROXY_VARS
from .fsutil import KIND_FILE, entry_kind, expand, is_under, read_text
from .platform import ISOLATION_ENV

MARKER_PREFIX = "# managed-by: multi-grok account="
LAUNCHER_PREFIX = "grok-"
LAUNCHER_MODE = 0o755

_NO_PROXY_HOSTS = "localhost,127.0.0.1,::1"

# grok 1.0.70 `grok --help` 里不接值的开关。最后一个固定参数若是其它选项且没有值，
# 用户接着传入的提示词会被这个选项吃掉。这份清单只用于告警，不参与解析。
BOOLEAN_FLAGS = frozenset([
    "--always-approve", "-c", "--continue", "--debug", "--disable-web-search",
    "--fork-session", "--fullscreen", "-h", "--help", "--include-partial-messages",
    "--minimal", "--no-alt-screen", "--no-plan", "--no-subagents", "--oauth",
    "--verbatim", "-v", "--version",
])


def launcher_path(bin_dir: str, name: str) -> str:
    return os.path.join(expand(bin_dir), LAUNCHER_PREFIX + name)


def expand_value(value: str) -> str:
    """值恰好是 `~` 或以 `~/` 开头时展开成绝对路径。`--settings=~/x` 这种不展开。"""
    if value == "~" or value.startswith("~/"):
        return os.path.expanduser(value)
    return value


def shell_account_dir(root: str, name: str) -> str:
    """启动脚本里 `account_dir=` 的右侧，已经是一段安全的 shell 词。

    账号目录在用户主目录下时写成 `"$HOME/..."`，不把某一次展开得到的绝对路径写死。
    账号名只允许 [A-Za-z0-9._@+-]，相对路径里不会出现空格或引号。
    """
    account_abs = os.path.join(expand(root), name)
    home = os.path.expanduser("~")
    if is_under(account_abs, home):
        relative = os.path.relpath(account_abs, home)
        if not relative.startswith("..") and os.sep + ".." not in os.sep + relative:
            return '"$HOME/{}"'.format(relative.replace(os.sep, "/"))
    return shlex.quote(account_abs)


def render(name: str, root: str, proxy: str, env: Dict[str, str], args: List[str], *,
           net_check: bool = False) -> str:
    """生成 POSIX sh 启动命令。插进脚本的值都经过 shlex.quote，账号目录表达式除外（它自己已加引号）。

    net_check 为真时在目录检查之后插入网络检查段（docs/feature/feature-network-check.md §5.1.3）；
    为假时输出与 0.3.0 逐字节相同，未开启检查的账号启动命令不会被判成“已变化”。
    """
    lines = [
        "#!/bin/sh",
        MARKER_PREFIX + name,
        "# Generated by multi-grok. Do not edit; use `multi-grok` commands to change it.",
        "account_dir=" + shell_account_dir(root, name),
        # -L 必须写在 -d 前面：指向目录的软链也能通过 [ -d ]。
        'if [ -L "$account_dir" ]; then',
        "  printf 'multi-grok: GROK_HOME must be a real directory, not a symlink: %s\\n' \"$account_dir\" >&2",
        "  exit 1",
        "fi",
        'if [ ! -d "$account_dir" ]; then',
        "  printf 'multi-grok: account directory does not exist: %s\\n' \"$account_dir\" >&2",
        "  exit 1",
        "fi",
    ]
    if net_check:
        lines.extend(_net_check_lines(name))
    lines.extend([
        'GROK_HOME="$account_dir"',
        "export GROK_HOME",
        # 父 shell 里导出的钥匙会让没登录的账号共用同一份凭据，或把登录指到别的文件。
        "unset " + " ".join(ISOLATION_ENV),
    ])
    for key in sorted(env):
        lines.append("{}={}; export {}".format(key, shlex.quote(expand_value(env[key])), key))
    lines.extend(_proxy_lines(proxy))
    command = ["exec", "grok"] + [shlex.quote(expand_value(arg)) for arg in args] + ['"$@"']
    lines.extend([
        "if ! command -v grok >/dev/null 2>&1; then",
        "  echo \"multi-grok: grok not found in PATH\" >&2",
        "  exit 127",
        "fi",
        " ".join(command),
        "",
    ])
    return "\n".join(lines)


def _net_check_lines(name: str) -> List[str]:
    """启动前网络检查段：检查不通过时以 multi-grok 的退出码（5）退出，grok 不会运行。

    在子 shell 里先 `cd /` 再运行：multi-grok 包装用 `python -m` 启动（install.sh），在用户项目目录里运行时
    项目里的 json.py、ssl.py 会顶替标准库。切目录只在子 shell 里生效，grok 仍在用户当前目录启动。
    检查跑在子进程里，删不掉本 shell 的跳过变量，所以通过后由这里 unset，grok 及其子进程不会继承“跳过”。
    """
    return [
        "if ! command -v multi-grok >/dev/null 2>&1; then",
        "  echo 'multi-grok: multi-grok not found in PATH; it runs the network check of this account' >&2",
        "  exit 127",
        "fi",
        "(cd / && exec multi-grok netgate {}) || exit $?".format(shlex.quote(name)),
        "unset " + NETCHECK_SKIP_ENV,
    ]


def _proxy_lines(proxy: str) -> List[str]:
    if proxy == PROXY_INHERIT:
        return []
    if proxy == PROXY_OFF:
        return ["unset " + " ".join(PROXY_VARS)]
    quoted = shlex.quote(proxy)
    return [
        "HTTPS_PROXY={0}; HTTP_PROXY={0}; https_proxy={0}; http_proxy={0}".format(quoted),
        "export HTTPS_PROXY HTTP_PROXY https_proxy http_proxy",
        "unset ALL_PROXY all_proxy",
        'NO_PROXY="${{NO_PROXY:+$NO_PROXY,}}{}"'.format(_NO_PROXY_HOSTS),
        'no_proxy="${{no_proxy:+$no_proxy,}}{}"'.format(_NO_PROXY_HOSTS),
        "export NO_PROXY no_proxy",
    ]


def trailing_option_warning(args: List[str]) -> Optional[str]:
    """最后一个固定参数会吃掉用户随后传入的词时，返回告警；否则返回 None。"""
    last_index = None
    for index, arg in enumerate(args):
        if arg.startswith("-") and arg != "--":
            last_index = index
    if last_index is None:
        return None
    token = args[last_index]
    if "=" in token or token in BOOLEAN_FLAGS or last_index < len(args) - 1:
        return None
    return ("{} is the last fixed argument and takes a value; the next word passed to the launcher "
            "would be consumed by it".format(token))


def managed_account(path: str) -> Optional[str]:
    """path 是本工具生成的启动命令时，返回标记里的账号名。软链和目录不算。"""
    if entry_kind(path) != KIND_FILE:
        return None
    content = read_text(path)
    if content is None:
        return None
    lines = content.split("\n", 2)
    if len(lines) < 2 or not lines[1].startswith(MARKER_PREFIX):
        return None
    return lines[1][len(MARKER_PREFIX):].strip() or None


def scan_managed(bin_dir: str) -> Dict[str, str]:
    """列出 bin_dir 里的受管启动命令，返回 {账号名: 路径}。目录不存在时返回空。"""
    found: Dict[str, str] = {}
    directory = expand(bin_dir)
    try:
        names = os.listdir(directory)
    except OSError:
        return found
    for entry in sorted(names):
        if not entry.startswith(LAUNCHER_PREFIX):
            continue
        path = os.path.join(directory, entry)
        account = managed_account(path)
        if account is not None:
            found[account] = path
    return found


def build_env(base: Dict[str, str], account_dir_path: str, proxy: str, extra: Dict[str, str]) -> Dict[str, str]:
    """给 `multi-grok login` 用的环境。与启动脚本清除和设置的变量一致。"""
    env = dict(base)
    for key in ISOLATION_ENV:
        env.pop(key, None)
    env["GROK_HOME"] = account_dir_path
    if proxy == PROXY_OFF:
        for key in PROXY_VARS:
            env.pop(key, None)
    elif proxy != PROXY_INHERIT:
        for key in ("HTTPS_PROXY", "HTTP_PROXY", "https_proxy", "http_proxy"):
            env[key] = proxy
        env.pop("ALL_PROXY", None)
        env.pop("all_proxy", None)
        env["NO_PROXY"] = _append_no_proxy(env.get("NO_PROXY", ""))
        env["no_proxy"] = _append_no_proxy(env.get("no_proxy", ""))
    for key in sorted(extra):
        env[key] = expand_value(extra[key])
    return env


def _append_no_proxy(current: str) -> str:
    if current:
        return current + "," + _NO_PROXY_HOSTS
    return _NO_PROXY_HOSTS
