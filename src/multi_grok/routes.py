"""按目录选择账号。`grok-auto` 是生成出来的 shell 入口。

启动时取当前目录的物理路径，在规则里找最长的祖先（含目录本身），转交对应的
`grok-<名称>`。没有命中时用默认账号；没设默认账号就直接运行 grok。
`resolve` 与脚本用同一条规则，测试会对拍。账号名 `auto` 保留给这个入口。
"""

import os
import shlex
from typing import List, Optional, Tuple

from .actions import CONFLICT, CREATE, DELETE, UNCHANGED, UPDATE, Action
from .config import Account, Config
from .fsutil import KIND_FILE, KIND_MISSING, entry_kind, expand, read_text, unlink_file
from .launcher import launcher_path

ROUTER_NAME = "grok-auto"
ROUTER_MARKER = "# managed-by: multi-grok router"
RESERVED_ACCOUNT = "auto"


def router_path(bin_dir: str) -> str:
    return os.path.join(expand(bin_dir), ROUTER_NAME)


def is_router(path: str) -> bool:
    """普通文件且第 2 行是路由标记。启动命令的标记不同，孤儿清理不会把它删掉。"""
    if entry_kind(path) != KIND_FILE:
        return False
    content = read_text(path)
    if content is None:
        return False
    lines = content.split("\n", 2)
    return len(lines) >= 2 and lines[1] == ROUTER_MARKER


def normalize_path(raw: str, cwd: str) -> str:
    """`~` 开头的路径保持原样，其余转成绝对路径，并去掉尾部斜杠。"""
    if raw == "~" or raw.startswith("~/"):
        return raw.rstrip("/") or "~"
    return os.path.normpath(os.path.join(cwd, raw)).rstrip("/") or "/"


def resolve(config: Config, directory: str) -> Tuple[Optional[Account], Optional[object]]:
    """返回 (账号或 None, 命中的规则或 None)。账号为 None 表示直接运行 grok。"""
    here = os.path.realpath(directory)
    best_rule = None
    best_length = 0
    for rule in config.route_rules:
        target = expand(rule.path)
        if not (os.path.isdir(target) and os.access(target, os.X_OK)):
            continue
        physical = os.path.realpath(target)
        if (here + "/").startswith(physical + "/") and len(physical) > best_length:
            best_rule, best_length = rule, len(physical)
    if best_rule is not None:
        return config.find(best_rule.account), best_rule
    if config.route_default is not None:
        return config.find(config.route_default), None
    return None, None


def render_router(config: Config) -> str:
    lines = [
        "#!/bin/sh",
        ROUTER_MARKER,
        "# Generated by multi-grok. Do not edit; use `multi-grok route` to change it.",
        "target=''",
    ]
    if config.route_rules:
        lines.extend([
            "here=$(pwd -P) || exit 1",
            "best=0",
        ])
    for rule in config.route_rules:
        launcher = _target_launcher(config, rule.account)
        lines.extend([
            "r=$(cd -P -- {} 2>/dev/null && pwd -P) || r=''".format(shlex.quote(expand(rule.path))),
            'if [ -n "$r" ]; then',
            '  case "$here/" in',
            '    "$r"/*) if [ "${{#r}}" -gt "$best" ]; then best=${{#r}}; target={}; fi ;;'.format(
                shlex.quote(launcher)),
            "  esac",
            "fi",
        ])
    if config.route_default is not None:
        lines.extend([
            'if [ -z "$target" ]; then',
            "  target={}".format(shlex.quote(_target_launcher(config, config.route_default))),
            "fi",
        ])
    lines.extend([
        'if [ -n "$target" ]; then',
        '  exec "$target" "$@"',
        "fi",
        "if ! command -v grok >/dev/null 2>&1; then",
        '  echo "multi-grok: grok not found in PATH" >&2',
        "  exit 127",
        "fi",
        'exec grok "$@"',
        "",
    ])
    return "\n".join(lines)


def router_status(config: Config) -> Optional[str]:
    """路由未启用时返回 None。否则是 ok、missing、stale 或 conflict。"""
    if not config.routes_enabled():
        return None
    path = router_path(config.bin_dir)
    if entry_kind(path) == KIND_MISSING:
        return "missing"
    if not is_router(path):
        return "conflict"
    current = read_text(path)
    if current == render_router(config) and os.access(path, os.X_OK):
        return "ok"
    return "stale"


def plan_router(config: Config) -> List[Action]:
    path = router_path(config.bin_dir)
    if not config.routes_enabled():
        if is_router(path):
            return [Action(DELETE, "router", path, "no routes are configured", _unlink(path))]
        return []
    expected = render_router(config)
    kind = entry_kind(path)
    if kind == KIND_MISSING:
        return [Action(CREATE, "router", path, run=_write(path, expected))]
    if kind != KIND_FILE or not is_router(path):
        return [Action(CONFLICT, "router", path, "grok-auto exists and is not the managed router")]
    if read_text(path) == expected:
        return [Action(UNCHANGED, "router", path)]
    return [Action(UPDATE, "router", path, run=_write(path, expected))]


def _target_launcher(config: Config, name: str) -> str:
    account = config.find(name)
    return launcher_path(expand(config.bin_dir), account.name if account else name)


def _write(path: str, text: str):
    def run() -> None:
        from .fsutil import atomic_write
        directory = os.path.dirname(path)
        if entry_kind(directory) == KIND_MISSING:
            os.makedirs(directory, exist_ok=True)
        atomic_write(path, text, mode=0o755)
    return run


def _unlink(path: str):
    def run() -> None:
        unlink_file(path)
    return run
